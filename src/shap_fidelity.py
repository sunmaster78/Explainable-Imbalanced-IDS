# ---------------------------------------------------------------------------
# Helper: Extract Base Tree Models
# ---------------------------------------------------------------------------

def _extract_base_models(models: Any) -> List[Any]:
    """Extract fitted base estimators from VotingClassifier, StackingClassifier, list, or dict."""
    if hasattr(models, "named_estimators_") and isinstance(models.named_estimators_, dict):
        return [est for est in models.named_estimators_.values() if est is not None]
    elif hasattr(models, "estimators_") and isinstance(models.estimators_, (list, tuple)):
        # For StackingClassifier, estimators_ contains base models; for VotingClassifier, base models
        return [est for est in models.estimators_ if est is not None]
    elif isinstance(models, dict):
        return list(models.values())
    elif isinstance(models, (list, tuple)):
        return list(models)
    else:
        return [models]


# ---------------------------------------------------------------------------
# Task 8.1: SHAP Helper
# ---------------------------------------------------------------------------

def get_mean_abs_shap(
    models: Any,
    X: Union[np.ndarray, pd.DataFrame],
    class_index: int = 1,
    max_samples: int = 200,
    feature_names: Optional[List[str]] = None,
    seed: int = 42,
) -> pd.Series:
    """
    Compute ensemble mean absolute SHAP values per feature for a target class.

    Runs shap.TreeExplainer separately on RandomForest, XGBoost, and LightGBM base models,
    handles varying SHAP output formats (list of arrays, 3D array, 2D array),
    computes mean absolute SHAP per feature for the requested class,
    normalizes each model's vector to sum to 1, and averages across models.

    Args:
        models: Fitted ensemble (VotingClassifier, StackingClassifier, list/dict of estimators).
        X: Input feature samples of shape (N, D).
        class_index: Target class index to explain (0-indexed).
        max_samples: Maximum number of rows to subsample for fast computation.
        feature_names: Optional list of feature names.
        seed: Random seed for subsampling.

    Returns:
        pd.Series of feature importances indexed by feature name, summing to 1.0.
    """
    if isinstance(X, pd.DataFrame):
        if feature_names is None:
            feature_names = list(X.columns)
        X_arr = X.to_numpy(dtype=np.float32)
    else:
        X_arr = np.asarray(X, dtype=np.float32)

    n_samples, n_features = X_arr.shape
    if feature_names is None:
        feature_names = [f"feature_{i}" for i in range(n_features)]

    # Subsample if necessary
    if n_samples > max_samples:
        rng = np.random.RandomState(seed)
        sub_indices = rng.choice(n_samples, size=max_samples, replace=False)
        X_eval = X_arr[sub_indices]
    else:
        X_eval = X_arr

    base_models = _extract_base_models(models)
    if not base_models:
        raise ValueError("No base models could be extracted from input models object.")

    model_importance_vectors = []

    for idx, model in enumerate(base_models):
        try:
            explainer = shap.TreeExplainer(model)
            sv = explainer.shap_values(X_eval)

            # Extract SHAP array for the target class across versions
            if isinstance(sv, list):
                # Older SHAP or multi-output: list of (N, D) arrays per class
                if class_index < len(sv):
                    class_sv = sv[class_index]
                elif len(sv) == 1:
                    class_sv = sv[0] if class_index == 1 else -sv[0]
                else:
                    class_sv = sv[0]
            elif isinstance(sv, np.ndarray):
                if sv.ndim == 3:
                    # Shape is typically (N, D, n_classes) or (N, n_classes, D)
                    if sv.shape[-1] > class_index:
                        class_sv = sv[:, :, class_index]
                    elif sv.shape[1] > class_index:
                        class_sv = sv[:, class_index, :]
                    else:
                        class_sv = sv[:, :, 0]
                elif sv.ndim == 2:
                    # Binary model (N, D)
                    class_sv = sv if class_index == 1 else -sv
                else:
                    class_sv = sv
            else:
                continue

            # Mean absolute SHAP per feature
            mean_abs = np.mean(np.abs(class_sv), axis=0)

            # Normalize to sum to 1.0
            sum_imp = float(np.sum(mean_abs))
            if sum_imp > 1e-12:
                norm_imp = mean_abs / sum_imp
            else:
                norm_imp = np.ones_like(mean_abs) / len(mean_abs)

            model_importance_vectors.append(norm_imp)

        except Exception as e:
            logger.warning(f"TreeExplainer failed for base model {type(model).__name__}: {e}")
            continue

    if not model_importance_vectors:
        logger.warning("All TreeExplainers failed; returning uniform feature attribution.")
        avg_vec = np.ones(n_features, dtype=np.float32) / n_features
    else:
        avg_vec = np.mean(model_importance_vectors, axis=0)

    # Final normalization
    total = float(np.sum(avg_vec))
    if total > 0:
        avg_vec = avg_vec / total

    return pd.Series(avg_vec, index=feature_names, name=f"importance_class_{class_index}")


def get_sample_shap_matrix(
    models: Any,
    X: Union[np.ndarray, pd.DataFrame],
    class_index: int = 1,
    max_samples: int = 200,
    seed: int = 42,
) -> np.ndarray:
    """
    Compute per-sample absolute SHAP matrix (N, D) averaged across base models.
    Enables instant vectorised bootstrap resampling without re-invoking tree explainers.
    """
    if isinstance(X, pd.DataFrame):
        X_arr = X.to_numpy(dtype=np.float32)
    else:
        X_arr = np.asarray(X, dtype=np.float32)

    n_samples, n_features = X_arr.shape
    if n_samples > max_samples:
        rng = np.random.RandomState(seed)
        sub_indices = rng.choice(n_samples, size=max_samples, replace=False)
        X_eval = X_arr[sub_indices]
    else:
        X_eval = X_arr

    base_models = _extract_base_models(models)
    sample_shap_matrices = []

    for model in base_models:
        try:
            explainer = shap.TreeExplainer(model)
            sv = explainer.shap_values(X_eval)

            if isinstance(sv, list):
                if class_index < len(sv):
                    class_sv = sv[class_index]
                elif len(sv) == 1:
                    class_sv = sv[0] if class_index == 1 else -sv[0]
                else:
                    class_sv = sv[0]
            elif isinstance(sv, np.ndarray):
                if sv.ndim == 3:
                    if sv.shape[-1] > class_index:
                        class_sv = sv[:, :, class_index]
                    elif sv.shape[1] > class_index:
                        class_sv = sv[:, class_index, :]
                    else:
                        class_sv = sv[:, :, 0]
                elif sv.ndim == 2:
                    class_sv = sv if class_index == 1 else -sv
                else:
                    class_sv = sv
            else:
                continue

            sample_shap_matrices.append(np.abs(class_sv))
        except Exception:
            continue

    if not sample_shap_matrices:
        return np.ones((len(X_eval), n_features), dtype=np.float32) / n_features

    # Average per-sample absolute SHAP across base models
    return np.mean(sample_shap_matrices, axis=0)


# ---------------------------------------------------------------------------
# Fidelity Metrics & Fast Bootstrap Confidence Intervals
# ---------------------------------------------------------------------------

def compute_attribution_fidelity(
    v_real: np.ndarray,
    v_syn: np.ndarray,
    top_k: int = 10,
) -> Dict[str, float]:
    """
    Calculate explanation fidelity scores between real and synthetic feature attribution vectors:
    1. Spearman rank correlation: Alignment of overall feature hierarchy.
    2. Top-K Jaccard overlap: Consistency of most critical identified features.
    3. Cosine similarity: High-dimensional geometric cosine alignment.
    """
    vr = np.asarray(v_real, dtype=np.float64)
    vs = np.asarray(v_syn, dtype=np.float64)

    # 1. Spearman Rank Correlation
    if np.all(vr == vr[0]) or np.all(vs == vs[0]):
        spearman_corr = 0.0
    else:
        res = stats.spearmanr(vr, vs)
        spearman_corr = float(res.correlation if hasattr(res, "correlation") else res.statistic)
        if np.isnan(spearman_corr):
            spearman_corr = 0.0

    # 2. Top-K Jaccard Overlap
    k = min(top_k, len(vr))
    top_real = set(np.argsort(vr)[-k:])
    top_syn = set(np.argsort(vs)[-k:])
    intersection = len(top_real & top_syn)
    union = len(top_real | top_syn)
    jaccard = float(intersection / union) if union > 0 else 0.0

    # 3. Cosine Similarity
    norm_r = np.linalg.norm(vr)
    norm_s = np.linalg.norm(vs)
    if norm_r > 1e-12 and norm_s > 1e-12:
        cosine = float(np.dot(vr, vs) / (norm_r * norm_s))
    else:
        cosine = 0.0

    return {
        "spearman": round(spearman_corr, 4),
        "jaccard_top10": round(jaccard, 4),
        "cosine": round(cosine, 4),
    }


def bootstrap_fidelity_ci(
    M_real: np.ndarray,
    M_syn: np.ndarray,
    n_bootstrap: int = 1000,
    top_k: int = 10,
    seed: int = 42,
) -> Dict[str, Tuple[float, float]]:
    """
    Calculate 95% bootstrap confidence intervals for fidelity metrics (1000 resamples).
    Uses precomputed sample-level absolute SHAP matrices for instant vectorised resampling.
    """
    rng = np.random.RandomState(seed)
    n_r = len(M_real)
    n_s = len(M_syn)

    spearmans = []
    jaccards = []
    cosines = []

    for _ in range(n_bootstrap):
        idx_r = rng.choice(n_r, size=n_r, replace=True)
        idx_s = rng.choice(n_s, size=n_s, replace=True)

        v_r = np.mean(M_real[idx_r], axis=0)
        v_s = np.mean(M_syn[idx_s], axis=0)

        # Normalize
        sr = np.sum(v_r)
        ss = np.sum(v_s)
        v_r = v_r / sr if sr > 0 else v_r
        v_s = v_s / ss if ss > 0 else v_s

        f_scores = compute_attribution_fidelity(v_r, v_s, top_k=top_k)
        spearmans.append(f_scores["spearman"])
        jaccards.append(f_scores["jaccard_top10"])
        cosines.append(f_scores["cosine"])

    def get_ci(vals: List[float]) -> Tuple[float, float]:
        arr = np.array(vals)
        low = float(np.percentile(arr, 2.5))
        high = float(np.percentile(arr, 97.5))
        return round(low, 4), round(high, 4)

    return {
        "spearman_ci": get_ci(spearmans),
        "jaccard_ci": get_ci(jaccards),
        "cosine_ci": get_ci(cosines),
    }


# ---------------------------------------------------------------------------
# Task 8.2: Run Fidelity Evaluation Suite (Claim 1)
# ---------------------------------------------------------------------------

def run_fidelity(
    data: Dict[str, Any],
    generator: Any,
    config: Dict[str, Any],
    seed: int = 42,
    n_bootstrap: int = 1000,
    max_eval_samples: int = 150,
) -> Tuple[pd.DataFrame, Dict[str, Dict[str, pd.Series]]]:
    """
    Execute Novelty Claim 1: SHAP Fidelity Comparison (Real vs WGAN-GP vs SMOTE vs ROS).

    1. Fits reference Stage 2 ensemble on REAL training attack data only (non-circular).
    2. Identifies minority attack classes below target sample count.
    3. Builds real held-out, WGAN-GP synthetic, SMOTE synthetic, and ROS sets.
    4. Extracts mean-abs-SHAP attribution vectors using the reference ensemble.
    5. Computes Spearman correlation, Top-10 Jaccard overlap, Cosine similarity,
       and 1000-resample bootstrap 95% confidence intervals.
    6. Saves 'shap_fidelity' table and publication bar charts.

    Returns:
        Tuple of (results_df, dict_of_importance_vectors)
    """
    set_seed(seed)
    logger.info("============================================================")
    logger.info("Executing Novelty Claim 1: SHAP Explanation Fidelity Audit")
    logger.info("============================================================")

    X_train = np.asarray(data["X_train"], dtype=np.float32)
    y_train_cat = np.asarray(data["y_train_cat"])
    y_train_bin = np.asarray(data["y_train_bin"])
    feature_names = data.get("feature_names", [f"feat_{i}" for i in range(X_train.shape[1])])
    onehot_groups = data.get("onehot_column_indices", {})

    # Held-out real samples from test set
    X_test = np.asarray(data["X_test"], dtype=np.float32)
    y_test_cat = np.asarray(data["y_test_cat"])

    # 1. Filter training attacks strictly (No Normal traffic in reference model)
    attack_mask = y_train_bin == 1
    X_train_att = X_train[attack_mask]
    y_train_att = y_train_cat[attack_mask]

    # Fit LabelEncoder on training attack classes
    le_ref = LabelEncoder()
    y_train_att_enc = le_ref.fit_transform(y_train_att)
    attack_classes = list(le_ref.classes_)
    n_classes = len(attack_classes)

    logger.info(
        f"Training non-circular reference Stage 2 ensemble on {len(X_train_att)} REAL attack rows "
        f"across {n_classes} classes: {attack_classes}"
    )

    ensemble_kind = config.get("ensemble", {}).get("kind", "voting")
    ref_ensemble = get_ensemble(
        kind=ensemble_kind,
        config=config,
        n_classes=n_classes,
        seed=seed,
    )
    ref_ensemble.fit(X_train_att, y_train_att_enc)
    logger.info("Reference Stage 2 ensemble fitted successfully.")

    # 2. Determine minority classes targeted for oversampling
    target_ratio = float(
        config.get("resampling", {}).get("target_ratio", config.get("target_ratio", 0.5))
    )
    class_counts = pd.Series(y_train_att).value_counts()
    max_count = class_counts.max()
    target_count = int(max_count * target_ratio)

    minority_classes = [c for c, cnt in class_counts.items() if cnt < target_count]
    if not minority_classes:
        # Fall back to smallest classes
        minority_classes = list(class_counts.tail(2).index)

    logger.info(
        f"Identified minority attack classes to evaluate: {minority_classes} "
        f"(target count={target_count})"
    )

    # Class map for generator
    class_map = {c: i for i, c in enumerate(attack_classes)}

    records = []
    importance_dict: Dict[str, Dict[str, pd.Series]] = {}

    for cls in minority_classes:
        cls_idx = class_map[cls]
        importance_dict[cls] = {}

        # Real held-out samples (prefer test set; fallback to train if test is empty)
        real_heldout_mask = y_test_cat == cls
        if np.sum(real_heldout_mask) >= 5:
            X_real_cls = X_test[real_heldout_mask]
        else:
            X_real_cls = X_train_att[y_train_att == cls]

        n_eval = min(len(X_real_cls), max_eval_samples)
        n_eval = max(n_eval, 30)

        # A. Synthetic Sets:
        # 1. WGAN-GP samples
        X_wgan_syn, _ = generate_samples(
            generator=generator,
            class_id=cls_idx,
            n=n_eval,
            config=config,
            onehot_groups=onehot_groups,
        )

        # 2. SMOTE samples
        try:
            X_smote_aug, y_smote_aug, is_smote_syn = smote_oversample(
                X=X_train_att,
                y=y_train_att,
                target_ratio=target_ratio,
                config=config,
                seed=seed,
            )
            syn_mask = (y_smote_aug == cls) & is_smote_syn
            if np.sum(syn_mask) >= 5:
                X_smote_syn = X_smote_aug[syn_mask][:n_eval]
            else:
                X_smote_syn = X_real_cls
        except Exception as e:
            logger.warning(f"SMOTE generation failed for {cls}: {e}. Using real fallback.")
            X_smote_syn = X_real_cls

        # 3. Random Oversampling samples
        X_ros_aug, y_ros_aug, is_ros_syn = random_oversample(
            X=X_train_att,
            y=y_train_att,
            target_ratio=target_ratio,
            config=config,
            seed=seed,
        )
        ros_mask = (y_ros_aug == cls) & is_ros_syn
        if np.sum(ros_mask) >= 5:
            X_ros_syn = X_ros_aug[ros_mask][:n_eval]
        else:
            X_ros_syn = X_real_cls

        # B. Compute Mean-Abs-SHAP Importance Vectors & Sample Matrices
        v_real = get_mean_abs_shap(ref_ensemble, X_real_cls, class_index=cls_idx, max_samples=n_eval, feature_names=feature_names, seed=seed)
        v_wgan = get_mean_abs_shap(ref_ensemble, X_wgan_syn, class_index=cls_idx, max_samples=n_eval, feature_names=feature_names, seed=seed)
        v_smote = get_mean_abs_shap(ref_ensemble, X_smote_syn, class_index=cls_idx, max_samples=n_eval, feature_names=feature_names, seed=seed)
        v_ros = get_mean_abs_shap(ref_ensemble, X_ros_syn, class_index=cls_idx, max_samples=n_eval, feature_names=feature_names, seed=seed)

        importance_dict[cls]["Real"] = v_real
        importance_dict[cls]["WGAN-GP"] = v_wgan
        importance_dict[cls]["SMOTE"] = v_smote
        importance_dict[cls]["ROS"] = v_ros

        # Sample matrices for bootstrap CIs
        M_real = get_sample_shap_matrix(ref_ensemble, X_real_cls, class_index=cls_idx, max_samples=n_eval, seed=seed)
        M_wgan = get_sample_shap_matrix(ref_ensemble, X_wgan_syn, class_index=cls_idx, max_samples=n_eval, seed=seed)
        M_smote = get_sample_shap_matrix(ref_ensemble, X_smote_syn, class_index=cls_idx, max_samples=n_eval, seed=seed)
        M_ros = get_sample_shap_matrix(ref_ensemble, X_ros_syn, class_index=cls_idx, max_samples=n_eval, seed=seed)

        # C. Compute Fidelity and Bootstrap 95% CIs
        methods_map = {
            "WGAN-GP": (v_wgan.values, M_wgan),
            "SMOTE": (v_smote.values, M_smote),
            "ROS": (v_ros.values, M_ros),
        }

        for m_name, (v_syn_arr, M_syn_arr) in methods_map.items():
            f_scores = compute_attribution_fidelity(v_real.values, v_syn_arr, top_k=10)
            ci_scores = bootstrap_fidelity_ci(M_real, M_syn_arr, n_bootstrap=n_bootstrap, seed=seed)

            records.append({
                "class": cls,
                "method": m_name,
                "spearman": f_scores["spearman"],
                "spearman_ci_low": ci_scores["spearman_ci"][0],
                "spearman_ci_high": ci_scores["spearman_ci"][1],
                "jaccard_top10": f_scores["jaccard_top10"],
                "jaccard_ci_low": ci_scores["jaccard_ci"][0],
                "jaccard_ci_high": ci_scores["jaccard_ci"][1],
                "cosine": f_scores["cosine"],
                "cosine_ci_low": ci_scores["cosine_ci"][0],
                "cosine_ci_high": ci_scores["cosine_ci"][1],
            })

            logger.info(
                f"  [{cls}] {m_name:7s} -> Spearman={f_scores['spearman']:.4f} "
                f"(95% CI: {ci_scores['spearman_ci']}) | Jaccard={f_scores['jaccard_top10']:.4f} | "
                f"Cosine={f_scores['cosine']:.4f}"
            )

        # D. Generate Side-by-Side Attribution Bar Plot
        plot_fidelity_bar(
            importance_dict[cls],
            class_name=cls,
            config=config,
            top_k=10,
        )

    # Save summary table
    df_results = pd.DataFrame(records)
    save_table(df_results, "shap_fidelity", config=config)
    logger.info("SHAP fidelity evaluation complete. Table saved to 'results/tables/shap_fidelity.csv'.")

    return df_results, importance_dict


# ---------------------------------------------------------------------------
# Attribution Plotting: Side-by-Side Bar Chart
# ---------------------------------------------------------------------------

def plot_fidelity_bar(
    importances: Dict[str, pd.Series],
    class_name: str,
    config: Optional[Dict[str, Any]] = None,
    top_k: int = 10,
) -> Path:
    """
    Generate and save a publication-quality side-by-side bar plot comparing
    top-10 feature attributions of Real vs WGAN-GP vs SMOTE vs ROS.
    """
    v_real = importances["Real"]
    # Pick top-K features from real held-out data
    top_features = list(v_real.nlargest(top_k).index)

    df_plot = pd.DataFrame({
        m_name: series.reindex(top_features, fill_value=0.0)
        for m_name, series in importances.items()
    })

    fig, ax = plt.subplots(figsize=(10, 6), dpi=300)
    x = np.arange(len(top_features))
    n_methods = len(df_plot.columns)
    width = 0.8 / n_methods

    # Color palette
    colors = ["#1f77b4", "#2ca02c", "#ff7f0e", "#9467bd"]

    for i, col in enumerate(df_plot.columns):
        ax.bar(
            x + (i - (n_methods - 1) / 2) * width,
            df_plot[col].values,
            width=width,
            label=col,
            color=colors[i % len(colors)],
            edgecolor="#222222",
            linewidth=0.8,
        )

    ax.set_xticks(x)
    ax.set_xticklabels(top_features, rotation=45, ha="right", fontsize=9, fontweight="bold")
    ax.set_ylabel("Mean Absolute SHAP (Normalized)", fontsize=11, fontweight="bold", labelpad=8)
    ax.set_xlabel("Top Real Predictive Features", fontsize=11, fontweight="bold", labelpad=8)
    ax.set_title(
        f"Feature Attribution Fidelity: Real vs Synthetic ({class_name})",
        fontsize=12,
        fontweight="bold",
        pad=10,
    )
    ax.legend(frameon=True, loc="upper right")
    ax.grid(axis="y", linestyle="--", alpha=0.5)

    plt.tight_layout()
    clean_name = class_name.lower().replace(" ", "_").replace("-", "_")
    out_path = save_figure(fig, f"shap_fidelity_{clean_name}", config=config, dpi=300)
    plt.close(fig)

    logger.info(f"Fidelity bar chart saved to: {out_path}")
    return out_path
