"""
SHAP Fidelity and Attribution Evaluation Module (Novelty Claim 1).

Evaluates whether synthetic minority attack samples generated by Conditional WGAN-GP
faithfully reproduce the feature attribution profiles and decision manifolds of real
network intrusions compared to conventional oversampling methods (SMOTE, Random Oversampling).

Key components:
1. get_mean_abs_shap: Unified TreeExplainer extractor across RF, XGBoost, and LightGBM
   handling heterogeneous SHAP tensor outputs and normalizing model attributions.
2. run_fidelity: Non-circular evaluation training a reference model on real attack rows only,
   evaluating Spearman rank correlation, top-10 Jaccard overlap, and cosine similarity with
   1000-sample bootstrap 95% confidence intervals and side-by-side attribution bar plots.
"""

